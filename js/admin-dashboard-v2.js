/* ==========================================================================
   Admin Dashboard V2 — visual helpers only.
   Adds stagger indices, count-up numbers, section re-entry animation and
   small nav count badges. No existing handlers, API calls or session logic
   are modified.
   ========================================================================== */
(function () {
    'use strict';

    if (!document.body || !document.body.classList.contains('adm-v2')) return;

    var reduceMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    var content = document.getElementById('adminContent');
    var badgeMap = { students: 0, faculty: 1, exams: 2, performance: 3, messages: 5 };

    function setIndex(el, index) {
        if (!el.style.getPropertyValue('--i')) el.style.setProperty('--i', String(index));
    }

    function animateValue(el) {
        if (el.getAttribute('data-v2-counted')) return;
        el.setAttribute('data-v2-counted', '1');
        if (reduceMotion) return;

        var original = el.textContent.trim();
        var match = original.match(/^([^\d]*)([\d,]+(?:\.\d+)?)([^\d]*)$/);
        if (!match) return;

        var end = parseFloat(match[2].replace(/,/g, ''));
        if (!isFinite(end)) return;

        var prefix = match[1];
        var suffix = match[3];
        var started = performance.now();
        var duration = 1100;

        function tick(now) {
            var progress = Math.min((now - started) / duration, 1);
            var eased = 1 - Math.pow(1 - progress, 3);
            var current = Math.round(end * eased).toLocaleString('en-IN');
            el.textContent = prefix + current + suffix;
            if (progress < 1) requestAnimationFrame(tick);
            else el.textContent = original;
        }

        requestAnimationFrame(tick);
    }

    function syncBadges() {
        var values = document.querySelectorAll('#ovStats .admin-stat-card__value');
        if (!values.length) return;

        Object.keys(badgeMap).forEach(function (section) {
            var item = document.querySelector('.admin-nav-item[data-section="' + section + '"]');
            var value = values[badgeMap[section]];
            if (!item || !value) return;

            var matched = value.textContent.match(/[\d,]+/);
            if (!matched) return;

            var badge = item.querySelector('.adm-v2-badge');
            if (!badge) {
                badge = document.createElement('span');
                badge.className = 'adm-v2-badge';
                item.appendChild(badge);
            }
            badge.textContent = matched[0];
        });
    }

    function decorateSection(section) {
        section.classList.add('adm-enter');
    }

    function decorate() {
        document.querySelectorAll('.admin-nav-item').forEach(setIndex);

        if (content) {
            content.querySelectorAll('.admin-card, .admin-stat-card').forEach(setIndex);
            content.querySelectorAll('.admin-bar-fill').forEach(setIndex);
            content.querySelectorAll('.admin-stat-card__value').forEach(animateValue);
        }

        document.querySelectorAll('.admin-section').forEach(decorateSection);
        syncBadges();
    }

    // Re-trigger the panel entrance whenever showSection() toggles [hidden].
    document.querySelectorAll('.admin-section').forEach(function (section) {
        if (!window.MutationObserver) return;
        new MutationObserver(function () {
            if (!section.hidden) {
                section.classList.remove('adm-enter');
                void section.offsetWidth;
                section.classList.add('adm-enter');
            }
        }).observe(section, { attributes: true, attributeFilter: ['hidden'] });
    });

    // Stat cards and bars are generated by the existing loaders after load.
    if (content && window.MutationObserver) {
        new MutationObserver(decorate).observe(content, { childList: true, subtree: true });
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', decorate, { once: true });
    } else {
        decorate();
    }
})();
